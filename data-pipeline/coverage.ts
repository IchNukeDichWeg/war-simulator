// Writes COVERAGE.md: which nations, snapshots and eras exist, with a confidence
// summary (share of grade A/B/C/D values) per snapshot, and what the plan still owes.
// Usage: tsx data-pipeline/coverage.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { EraId, Snapshot } from '../src/types/schema';
import { ROOT } from './lib/util';
import { confidence, gradeLetter, listJson } from './validate';
import { ERAS } from './schema';
import { EXCLUDE, MIN_AREA_KM2, enumerate, eraOf as hbEraOf, existingCoverage, norm } from './phase3-enumerate';

const plan = JSON.parse(readFileSync(join(ROOT, 'data', 'reference', 'coverage-plan.json'), 'utf8'));
const states = JSON.parse(readFileSync(join(ROOT, 'data', 'reference', 'states.json'), 'utf8')).states as { nationId: string; name: string }[];
const snaps: Snapshot[] = listJson('raw/snapshots').map((f) => JSON.parse(readFileSync(f, 'utf8')));
const doctrines = listJson('doctrine').length;
const battles = listJson('battles').length;

const grades = (s: Snapshot) => confidence(s);
const kind = (s: Snapshot) => s.tags.includes('auto-base') ? 'auto-base' : s.tags.includes('phase3') ? 'phase 3 (derived)' : 'researched';
const pct = (x: number, n: number) => `${Math.round((100 * x) / n)}%`;
const letter = gradeLetter;

const lines: string[] = [];
lines.push('# Coverage', '', `Generated by \`data-pipeline/coverage.ts\` from \`data/raw/snapshots\`. Do not edit by hand.`, '');
const byKind = (k: string) => snaps.filter((s) => kind(s) === k).length;
lines.push(`- Snapshots: **${snaps.length}** (${byKind('researched')} researched, ${byKind('auto-base')} auto-base modern, ${byKind('phase 3 (derived)')} phase-3 derived)`);
lines.push(`- Nations: **${new Set(snaps.map((s) => s.nationId)).size}**`);
lines.push(`- Doctrine profiles: **${doctrines}**, backtest cases: **${battles}**`);
const modernIds = new Set(snaps.filter((s) => s.year >= 2020).map((s) => s.nationId));
const missingModern = states.filter((s) => !modernIds.has(s.nationId));
lines.push(`- Modern states (UN 193 + 4): **${states.length - missingModern.length} / ${states.length}**${missingModern.length ? ` (missing: ${missingModern.map((s) => s.name).join(', ')})` : ''}`);
const planned = (plan.historical as { nationId: string; years: number[]; name: string }[]).flatMap((h) => h.years.map((y) => ({ id: `${h.nationId}-${y}`, name: `${h.name} ${y < 0 ? `${-y} BCE` : y}` })));
const have = new Set(snaps.map((s) => s.id));
const owed = planned.filter((p) => !have.has(p.id));
lines.push(`- Planned major historical snapshots: **${planned.length - owed.length} / ${planned.length}**`);
lines.push('', 'Confidence score = mean grade over every numeric value (A=4 ... D=1), shown as the nearest letter.', '');

// Phase 3: what the derived layer covers and what the enumeration leaves out on purpose.
{
  const { all, dropped } = await enumerate();
  const { years } = existingCoverage();
  const kept = all.filter((c) => c.areaKm2 >= MIN_AREA_KM2);
  const sameEra = kept.filter((c) => (years.get(norm(c.name)) ?? []).some((y) => hbEraOf(y) === c.era)).length;
  const p3 = snaps.filter((s) => s.tags.includes('phase3'));
  const kinds = ['state', 'indigenous', 'colonial', 'successor', 'settler'];
  lines.push('## Phase 3 (derived from historical-basemaps)', '',
    `Every historical-basemaps polity of at least ${MIN_AREA_KM2.toLocaleString('en-US')} km2 without a snapshot, one per polity per era at its largest extent (\`data-pipeline/phase3-enumerate.ts\`), derived by \`data-pipeline/generate-phase3.ts\` from \`data/reference/phase3-inputs.json\`. Low confidence: area, region and year only; methods in data/SOURCES.md "Phase 3 derivation inputs".`, '',
    `- Derived snapshots: **${p3.length}** of ${kept.length} enumerated polity-eras (${sameEra} skipped: a same-name snapshot exists in that era)`,
    `- Below ${MIN_AREA_KM2.toLocaleString('en-US')} km2, not derived: ${all.length - kept.length} polity-eras`, '',
    `| Era | Derived | ${kinds.join(' | ')} | Mean confidence |`, `| --- | --- | ${kinds.map(() => '---').join(' | ')} | --- |`);
  for (const era of ERAS as readonly EraId[]) {
    const e = p3.filter((s) => s.era === era);
    const mean = e.length ? e.reduce((a, s) => a + grades(s).score, 0) / e.length : 0;
    lines.push(`| ${era} | ${e.length} | ${kinds.map((k) => e.filter((s) => s.tags[2] === k).length).join(' | ')} | ${e.length ? `${letter(mean)} (${mean.toFixed(2)})` : '-'} |`);
  }
  const tagged = (re: RegExp) => p3.filter((s) => re.test(s.notes)).length;
  lines.push('', '### Known limits', '',
    `- Population: a modern country's OWID population where polity and country overlap mutually by 70% (${p3.filter((s) => s.demography.population.source === 'derived:country-population-match').length} snapshots), else habitable land (outside Koppen zone E) x regional density x state-density factor, bounded by the regional total. Without a match desert counts as habitable, so fragments or supersets of desert countries (the 1945 Libya pieces, Western Sahara, Arabia 1878, Air) keep regional densities far above plausible values, and a union matched to one member (Denmark-Norway to Norway) leaves the others out.`,
    `- No horses (cavalry, chariots, draft animals 0) in ${tagged(/No horses/)} polities before contact (Americas before 1493, Oceania before 1788). Post-contact horse adoption dates are not modelled per people: later polities take the peer pool's cavalry share.`,
    `- ${tagged(/No sea access/)} snapshots have no sea access (lake shores do not count) and field no ships.`,
    '- Open: cavalry of Sub-Saharan forest-zone states (Asante and similar) comes from the regional peer pool; no fetched source on their horse use was applied.');
  lines.push('', '### Not modelled', '', 'Basemap features excluded as non-state labels (distinct NAMEs over all basemap years):', '', '| Rule | Names | Why |', '| --- | --- | --- |');
  const why = new Map<string, string>();
  for (const e of EXCLUDE) why.set(e.id, why.has(e.id) ? `${why.get(e.id)}; ${e.reason}` : e.reason);
  why.set('indigenous-territory', 'Native-Land-style Indigenous land polygons after 1492 in Australia, North America north of the Tropic of Cancer and South America: peoples\' lands, not state borders (named state-like polities such as the Iroquois, Mapuche, Chimu and Muisca are kept)');
  for (const [id, w] of why) lines.push(`| ${id} | ${dropped.get(id)?.size ?? 0} | ${w} |`);
  lines.push('');
}

lines.push('## By era', '', '| Era | Snapshots | Researched | Mean confidence |', '| --- | --- | --- | --- |');
for (const era of ERAS as readonly EraId[]) {
  const e = snaps.filter((s) => s.era === era);
  const r = e.filter((s) => kind(s) === 'researched');
  const mean = e.length ? e.reduce((a, s) => a + grades(s).score, 0) / e.length : 0;
  lines.push(`| ${era} | ${e.length} | ${r.length} | ${e.length ? `${letter(mean)} (${mean.toFixed(2)})` : '-'} |`);
}

lines.push('', '## Snapshots', '', '| Snapshot | Year | Era | Region | Kind | A | B | C | D | Confidence |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const s of [...snaps].sort((a, b) => a.year - b.year || a.id.localeCompare(b.id))) {
  const { g, n, score } = grades(s);
  lines.push(`| ${s.name} (\`${s.id}\`) | ${s.year < 0 ? `${-s.year} BCE` : s.year} | ${s.era} | ${s.region} | ${kind(s)} | ${pct(g.A, n)} | ${pct(g.B, n)} | ${pct(g.C, n)} | ${pct(g.D, n)} | ${letter(score)} |`);
}
if (owed.length) {
  lines.push('', '## Still owed (planned, not yet researched)', '');
  for (const o of owed) lines.push(`- ${o.name} (\`${o.id}\`)`);
}
writeFileSync(join(ROOT, 'COVERAGE.md'), lines.join('\n') + '\n');
console.log(`COVERAGE.md: ${snaps.length} snapshots, ${owed.length} planned still owed, ${missingModern.length} modern states missing`);
